# -*- coding: utf-8 -*-
"""
Кодировщик штрихкодов Code 128.

Своя реализация, без внешних зависимостей: библиотека python-barcode не входит
в поставку, а тащить ради ста строк ещё один пакет в установщик не нужно.
Формат Code 128 выбран потому, что его понимают практически все складские
сканеры, он кодирует и цифры, и латиницу, и содержит контрольную сумму.

Модуль возвращает список ширин штрихов: [(чёрный?, ширина в модулях), ...].
Рисование (PNG или PDF) выполняется в barcode_service.
"""
from __future__ import annotations

from typing import List, Tuple

# Ширины элементов для значений 0..106. Каждая строка — 6 (у STOP 7) элементов,
# начиная с чёрного штриха: чёрный, пробел, чёрный, пробел, чёрный, пробел.
_PATTERNS = [
    "212222", "222122", "222221", "121223", "121322", "131222", "122213", "122312",
    "132212", "221213", "221312", "231212", "112232", "122132", "122231", "113222",
    "123122", "123221", "223211", "221132", "221231", "213212", "223112", "312131",
    "311222", "321122", "321221", "312212", "322112", "322211", "212123", "212321",
    "232121", "111323", "131123", "131321", "112313", "132113", "132311", "211313",
    "231113", "231311", "112133", "112331", "132131", "113123", "113321", "133121",
    "313121", "211331", "231131", "213113", "213311", "213131", "311123", "311321",
    "331121", "312113", "312311", "332111", "314111", "221411", "431111", "111224",
    "111422", "121124", "121421", "141122", "141221", "112214", "112412", "122114",
    "122411", "142112", "142211", "241211", "221114", "413111", "241112", "134111",
    "111242", "121142", "121241", "114212", "124112", "124211", "411212", "421112",
    "421211", "212141", "214121", "412121", "111143", "111341", "131141", "114113",
    "114311", "411113", "411311", "113141", "114131", "311141", "411131", "211412",
    "211214", "211232", "2331112",
]

START_B = 104
START_C = 105
STOP = 106

QUIET_ZONE_MODULES = 10   # обязательное пустое поле слева и справа по стандарту


class BarcodeError(ValueError):
    """Значение невозможно закодировать в Code 128."""


def _values_code_c(text: str) -> List[int]:
    return [START_C] + [int(text[i:i + 2]) for i in range(0, len(text), 2)]


def _values_code_b(text: str) -> List[int]:
    values = [START_B]
    for ch in text:
        code = ord(ch)
        if not 32 <= code <= 126:
            raise BarcodeError(
                f"Символ «{ch}» нельзя закодировать в Code 128. "
                "Допустимы латинские буквы, цифры и знаки препинания.")
        values.append(code - 32)
    return values


def encode_values(text: str) -> List[int]:
    """
    Значения символов вместе со стартовым, контрольной суммой и стопом.

    Чисто числовое значение чётной длины кодируется набором C (две цифры на
    символ — штрихкод получается вдвое короче и лучше читается сканером),
    всё остальное — набором B.
    """
    if not text:
        raise BarcodeError("Пустое значение штрихкода.")
    if text.isdigit() and len(text) % 2 == 0:
        values = _values_code_c(text)
    else:
        values = _values_code_b(text)
    checksum = values[0]
    for position, value in enumerate(values[1:], start=1):
        checksum += position * value
    values.append(checksum % 103)
    values.append(STOP)
    return values


def encode_bars(text: str) -> List[Tuple[bool, int]]:
    """
    Список элементов штрихкода: (True — чёрный штрих, ширина в модулях).
    Тихие зоны в список не включаются, их добавляет рисующий код.
    """
    bars: List[Tuple[bool, int]] = []
    for value in encode_values(text):
        black = True
        for width in _PATTERNS[value]:
            bars.append((black, int(width)))
            black = not black
    return bars


def total_modules(text: str) -> int:
    """Полная ширина кода в модулях, включая тихие зоны."""
    return sum(width for _, width in encode_bars(text)) + 2 * QUIET_ZONE_MODULES


def is_encodable(text: str) -> bool:
    try:
        encode_values(text)
        return True
    except BarcodeError:
        return False
