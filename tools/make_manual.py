def st(name, size=10, bold=False, align=TA_LEFT, leading=None, space=4, color=colors.black,
       left=0, right=0):
    return ParagraphStyle(name, parent=base, fontName="Man-Bold" if bold else "Man",
                          fontSize=size, leading=leading or size * 1.45, alignment=align,
                          spaceAfter=space, textColor=color, leftIndent=left, rightIndent=right)


