def _decor(canvas, doc):
    """Колонтитул: слева название, справа номер страницы. Работает и на альбомных."""
    if canvas.getPageNumber() == 1:
        return
    width = doc.pagesize[0]
    canvas.saveState()
    canvas.setFont("Man", 7.5)
    canvas.setFillColor(MUTED)
    canvas.drawString(18 * mm, 10 * mm, f"{DISPLAY_NAME} — руководство пользователя")
    canvas.drawRightString(width - 18 * mm, 10 * mm, str(canvas.getPageNumber()))
    canvas.setStrokeColor(BORDER)
    canvas.line(18 * mm, 13 * mm, width - 18 * mm, 13 * mm)
    canvas.restoreState()


def make_doc(target: Path) -> BaseDocTemplate:
    """Книжные страницы для текста и альбомные — для широких схем экранов."""
    doc = BaseDocTemplate(str(target), pagesize=A4,
                          title=f"{DISPLAY_NAME} — руководство пользователя",
                          author="Склад Реквизита")
    portrait_frame = Frame(18 * mm, 18 * mm, A4[0] - 36 * mm, A4[1] - 34 * mm, id="portrait")
    land = landscape(A4)
    landscape_frame = Frame(15 * mm, 18 * mm, land[0] - 30 * mm, land[1] - 32 * mm, id="landscape")
    doc.addPageTemplates([
        PageTemplate(id="portrait", frames=[portrait_frame], pagesize=A4, onPage=_decor),
        PageTemplate(id="landscape", frames=[landscape_frame], pagesize=land, onPage=_decor),
    ])
    return doc


def screen(name: str, caption: str, width_mm: float = 168) -> list:
    """Вставляет изображение экрана с подписью, сохраняя пропорции."""
    path = SCREENS / name
    if not path.exists():
        return [Paragraph(f"[нет изображения {name}]", S["note"])]
    from PIL import Image as PILImage
    with PILImage.open(path) as img:
        ratio = img.height / img.width
    width = width_mm * mm
    picture = Image(str(path), width=width, height=width * ratio)
    picture.hAlign = "CENTER"
    return [Spacer(1, 2 * mm), picture, Paragraph(caption, S["cap"])]


def wide_screen(name: str, caption: str, items: list[tuple[str, str]],
                heading: str = "", intro: str = "") -> list:
    """
    Широкая схема экрана на отдельной альбомной странице — чтобы всё читалось.

    Размер картинки подбирается расчётом: замеряется высота заголовка, вводного
    абзаца, подписи и расшифровки выносок, а изображению отдаётся всё остальное.
    Так схема всегда помещается на одну страницу целиком.
    """
    land = landscape(A4)
    frame_w = land[0] - 30 * mm
    frame_h = land[1] - 32 * mm

    parts: list = []
    if heading:
        parts.append(Paragraph(heading, S["h1"]))
    if intro:
        parts.append(Paragraph(intro, S["p"]))
    caption_flow = Paragraph(caption, S["cap"])
    callout_flow = callouts(items, width=frame_w) if items else None

    used = sum(p.wrap(frame_w, frame_h)[1] + p.getSpaceAfter() for p in parts)
    used += caption_flow.wrap(frame_w, frame_h)[1] + caption_flow.getSpaceAfter()
    if callout_flow is not None:
        used += callout_flow.wrap(frame_w, frame_h)[1]
    used += 14 * mm                    # отступы вокруг картинки и запас на округления

    from PIL import Image as PILImage
    with PILImage.open(SCREENS / name) as img:
        ratio = img.height / img.width
    width = min(frame_w, (frame_h - used) / ratio)
    if DEBUG:
        print(f"{name}: занято {used/mm:.0f} мм, картинка {width/mm:.0f}×{width*ratio/mm:.0f} мм, "
              f"итого {(used + width*ratio)/mm:.0f} из {frame_h/mm:.0f}")

    picture = Image(str(SCREENS / name), width=width, height=width * ratio)
    picture.hAlign = "CENTER"

    block: list = [NextPageTemplate("landscape"), PageBreak()]
    block += parts
    block += [Spacer(1, 2 * mm), picture, caption_flow]
    if callout_flow is not None:
        block.append(callout_flow)
    block += [NextPageTemplate("portrait"), PageBreak()]
    return block


def collapse_breaks(story: list) -> list:
    """
    Убирает двойные переводы страниц: если раздел закончился разрывом, а следующий
    начинается со своего разрыва, между ними появлялась пустая страница.
    """
    result: list = []
    for i, item in enumerate(story):
        if isinstance(item, PageBreak):
            rest = story[i + 1:]
            j = 0
            while j < len(rest) and isinstance(rest[j], NextPageTemplate):
                j += 1
            if j < len(rest) and isinstance(rest[j], PageBreak):
                continue          # следующий разрыв сделает всю работу
        result.append(item)
    return result


def steps(items: list[str]) -> ListFlowable:
    return ListFlowable([ListItem(Paragraph(text, S["li"]), leftIndent=14)
                         for text in items], bulletType="1", start="1",
                        bulletFontName="Man-Bold", bulletFontSize=10, leftIndent=16)


def bullets(items: list[str]) -> ListFlowable:
    return ListFlowable([ListItem(Paragraph(text, S["li"]), leftIndent=12)
                         for text in items], bulletType="bullet", bulletFontName="Man",
                        bulletFontSize=9, leftIndent=14)


def callouts(items: list[tuple[str, str]], width=None) -> Table:
    """Расшифровка выносок на схеме экрана."""
    rows = [[Paragraph(f"<b>{n}</b>", S["cell"]), Paragraph(text, S["cell"])] for n, text in items]
    table = Table(rows, colWidths=[9 * mm, (width - 9 * mm) if width else None])
    table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 2),
        ("TOPPADDING", (0, 0), (-1, -1), 2),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
        ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#c62828")),
    ]))
    return table


def infobox(title: str, text: str, color=LIGHT) -> Table:
    inner = [[Paragraph(f"<b>{title}</b><br/>{text}", S["cell"])]]
    table = Table(inner, colWidths=[168 * mm])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), color),
        ("BOX", (0, 0), (-1, -1), 0.5, BORDER),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
    ]))
    return table


